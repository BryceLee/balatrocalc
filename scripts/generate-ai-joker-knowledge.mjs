import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cardsSource = readFileSync(join(root, 'cards.js'), 'utf8');
const descriptions = new Map();
const aliases = new Map();
const localizedAliasOwners = new Map();

function cleanDescription(value) {
  return value
    .replaceAll('\\n', ' ')
    .replace(/<br\s*\/?\s*>/gi, ' ')
    .replace(/\$\{prodc\}/g, 'X')
    .replace(/\$\{(?:multc|endc|numc|chipc|moneyc|shadowc|probc|diamondc|heartc|spadec|clubc|tarotc|spectralc|planetc|roomc|commonc)\}/g, '')
    .replace(/\$\{[^}]+\}/g, '[run-dependent value]')
    .replace(/\\'/g, "'")
    .replace(/\s+/g, ' ')
    .trim();
}

const entryPattern = /^\s*\[(['"])(.*?)\1,\s*(['"])((?:\\.|(?!\3).)*)\3/gm;
for (const match of cardsSource.matchAll(entryPattern)) {
  const name = match[2].trim();
  if (!name || descriptions.has(name)) continue;
  descriptions.set(name, cleanDescription(match[4]));
  aliases.set(name, new Set([name]));
}

const compatibility = new Map();
const definitionPattern = /^j_[a-z0-9_]+\s*=\s*\{[^\n]*blueprint_compat\s*=\s*(true|false)[^\n]*name\s*=\s*(['"])(.*?)\2/gm;
for (const match of cardsSource.matchAll(definitionPattern)) {
  compatibility.set(match[3], match[1] === 'true');
}

for (const filename of readdirSync(join(root, 'assets/i18n'))) {
  if (!filename.endsWith('.json')) continue;
  const locale = JSON.parse(readFileSync(join(root, 'assets/i18n', filename), 'utf8'));
  for (const entry of Object.values(locale?.descriptions?.Joker || {})) {
    const englishName = String(entry?.en_name || '').trim();
    const localizedName = String(entry?.name || '').trim();
    if (!aliases.has(englishName) || !localizedName) continue;
    const owners = localizedAliasOwners.get(localizedName) || new Set();
    owners.add(englishName);
    localizedAliasOwners.set(localizedName, owners);
  }
}

for (const [localizedName, owners] of localizedAliasOwners) {
  if (owners.size !== 1) continue;
  aliases.get(Array.from(owners)[0]).add(localizedName);
}

if (descriptions.size !== 150) {
  throw new Error(`Expected 150 Joker descriptions, found ${descriptions.size}`);
}

const catalog = Array.from(descriptions, ([name, description]) => ({
  name,
  description,
  blueprintCompatible: compatibility.get(name) ?? null,
  aliases: Array.from(aliases.get(name) || [name])
}));

const output = `// Generated by scripts/generate-ai-joker-knowledge.mjs. Do not edit by hand.\n` +
  `export const JOKER_KNOWLEDGE = Object.freeze(${JSON.stringify(catalog, null, 2)});\n`;

writeFileSync(join(root, 'functions/api/ai/_joker-knowledge.generated.js'), output);
console.log(`Generated ${catalog.length} grounded Joker entries.`);
